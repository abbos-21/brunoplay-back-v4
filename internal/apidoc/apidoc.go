// Package apidoc writes the API reference and the settings reference from the code itself, so the documents can never drift
// from what the server really does.
package apidoc

import (
	"fmt"
	"net/http"
	"sort"
	"strings"

	"github.com/go-chi/chi/v5"

	"brunoplay/internal/settings"
)

type route struct{ method, path string }

func class(path string) string {
	switch {
	case strings.HasPrefix(path, "/api/admin/auth"):
		return "public (admin sign-in)"
	case strings.HasPrefix(path, "/api/admin"):
		return "admin"
	case strings.HasPrefix(path, "/api/webhooks"):
		return "webhook (secret)"
	case path == "/api/app-info" || path == "/api/auth/telegram" || path == "/api/auth/dev" || path == "/healthz" || path == "/readyz":
		return "public"
	}
	return "player"
}

// Routes lists every route of the router, sorted.
func Routes(r chi.Router) []route {
	var out []route
	_ = chi.Walk(r, func(method, rt string, _ http.Handler, _ ...func(http.Handler) http.Handler) error {
		out = append(out, route{method, strings.TrimSuffix(rt, "/")})
		return nil
	})
	sort.Slice(out, func(i, j int) bool {
		if out[i].path != out[j].path {
			return out[i].path < out[j].path
		}
		return out[i].method < out[j].method
	})
	return out
}

// API renders the route reference as Markdown.
func API(r chi.Router) string {
	var b strings.Builder
	b.WriteString("# BrunoPlay API reference (generated)\n\n")
	b.WriteString("Generated by `brunoplay docs` from the real router. Request and response shapes are described in `docs/FRONTEND-INTEGRATION.md`; ")
	b.WriteString("every error is `{ \"error\": { \"code\", \"message\", \"params\", \"requestId\" } }` with the message in the player's language.\n\n")
	b.WriteString("Access: **public** needs nothing; **player** needs `Authorization: Bearer <player token>` (from `POST /api/auth/telegram`); ")
	b.WriteString("**admin** needs an admin access token and the role's permission; **webhook** needs the shared secret.\n\n")
	routes := Routes(r)
	groups := []struct{ title, prefix string }{
		{"Public and player API", "/api/"},
		{"Admin API", "/api/admin"},
	}
	for _, g := range groups {
		b.WriteString("## " + g.title + "\n\n| Method | Path | Access |\n|---|---|---|\n")
		for _, rt := range routes {
			isAdmin := strings.HasPrefix(rt.path, "/api/admin")
			if (g.prefix == "/api/admin") != isAdmin {
				continue
			}
			fmt.Fprintf(&b, "| %s | `%s` | %s |\n", rt.method, rt.path, class(rt.path))
		}
		b.WriteString("\n")
	}
	b.WriteString("## Health\n\n| Method | Path |\n|---|---|\n| GET | `/healthz` |\n| GET | `/readyz` |\n")
	return b.String()
}

// Settings renders the table of every setting the owner can edit.
func Settings() string {
	var b strings.Builder
	b.WriteString("# Settings reference (generated)\n\nEvery value the owner supplies or changes in the admin panel (`PUT /api/admin/settings/{key}`). ")
	b.WriteString("**Required** means there is no default: the feature that needs it answers `CONFIG_MISSING` until it is set.\n\n")
	defs := settings.Registry()
	sort.Slice(defs, func(i, j int) bool {
		if defs[i].Group != defs[j].Group {
			return defs[i].Group < defs[j].Group
		}
		return defs[i].Key < defs[j].Key
	})
	group := ""
	for _, d := range defs {
		if d.Group != group {
			group = d.Group
			fmt.Fprintf(&b, "\n## %s\n\n| Key | Type | Default | What it is |\n|---|---|---|---|\n", group)
		}
		def := "**required**"
		if d.Default != nil {
			def = fmt.Sprintf("`%v`", d.Default)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", d.Key, d.Kind, def, strings.ReplaceAll(d.Desc, "|", "/"))
	}
	return b.String()
}
